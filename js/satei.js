  function createSchema() {
    DDL.split(";")
      .map((s) => s.trim())
      .filter((s) => s.length)
      .forEach((stmt) => Database.run(stmt + ";"));
  }

  /**
   * 公表データを投入する。既に投入済みの行 (同一キー) は重複させない。
   * @returns {{sources:number, metrics:number, stats:number, prefs:number}}
   */
  function seed() {
    createSchema();
    const prefCode = {};
    if (typeof Schema !== "undefined") {
      Schema.PREFECTURES.forEach(([code, name]) => (prefCode[name] = code));
    }
    const counts = { sources: 0, metrics: 0, stats: 0, prefs: 0 };
    Database.run("BEGIN TRANSACTION");
    try {
      SOURCES.forEach((r) => {
        Database.run(
          "INSERT OR REPLACE INTO 査定返戻_出典 (出典ID, 資料名, 発行元, 公表年月, URL, 備考) VALUES (?,?,?,?,?,?)",
          r
        );
        counts.sources++;
      });
      METRICS.forEach((r) => {
        Database.run(
          "INSERT OR REPLACE INTO 査定返戻_指標定義 (指標, 定義, 単位) VALUES (?,?,?)",
          r
        );
        counts.metrics++;
      });
      STATS.forEach((r) => {
        const exists = Database.scalar(
          "SELECT COUNT(*) FROM 査定返戻_統計 WHERE 審査機関=? AND 対象期間=? AND 診療種別=? AND 審査区分=? AND 指標=? AND 出典ID=?",
          [r[0], r[1], r[3], r[4], r[5], r[9]]
        );
        if (exists) return;
        Database.run(
          "INSERT INTO 査定返戻_統計 (審査機関, 対象期間, 期間種別, 診療種別, 審査区分, 指標, 値, 単位, 前年比, 出典ID, 備考) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
          r
        );
        counts.stats++;
      });
      PREF_STATS.forEach((r) => {
        const exists = Database.scalar(
          "SELECT COUNT(*) FROM 査定返戻_都道府県 WHERE 都道府県名=? AND 審査機関=? AND 対象期間=? AND 診療種別=? AND 審査区分=? AND 指標=?",
          [r[0], r[1], r[2], r[3], r[4], r[5]]
        );
        if (exists) return;
        Database.run(
          "INSERT INTO 査定返戻_都道府県 (都道府県コード, 都道府県名, 審査機関, 対象期間, 診療種別, 審査区分, 指標, 値, 単位, 出典ID, 備考) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
          [prefCode[r[0]] || null, ...r]
        );
        counts.prefs++;
      });
      Database.run("COMMIT");
    } catch (e) {
      Database.run("ROLLBACK");
      throw e;
    }
    return counts;
  }

  /** 査定返戻テーブルが存在するか。 */
  function isLoaded() {
    const tables = Database.listTables();
    return tables.includes("査定返戻_統計") && tables.includes("査定返戻_出典");
  }

